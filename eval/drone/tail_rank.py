#!/usr/bin/env python3
"""Score candidate offline statistics against the MEASURED closed-loop ordering.

Reads the per-frame summaries from `tail_metrics.py` and asks, for every candidate statistic:
does it order the arms the way the drone actually flew?

The test is deliberately PER CLASS and PAIRWISE, not a global 4-arm ranking. A global ranking over
4 arms is 24 orderings and would be matched by chance far too often; the per-class table gives ~26
independent arm-vs-arm comparisons including two reversals that no mean statistic reproduces
(top-2 owns umbrella, top-1 owns clothes_hanger_02). A statistic that reproduces those is saying
something real.

Hazard convention: every candidate is oriented so LOWER = safer. Concordance means the safer arm
is the one that actually navigated better.

Honest accounting of the multiple-comparison exposure: this sweeps many candidates and then reports
the best, so the headline concordance is optimistically biased. Two guards are printed -- the total
number of candidates swept, and a split validation that selects the winner on one half of the
classes and scores it on the held-out half.
"""
import argparse
import json
import math
from collections import defaultdict

import numpy as np

QS = [0.50, 0.75, 0.90, 0.95, 0.99]
TAUS = [0.10, 0.15, 0.20, 0.27, 0.35, 0.50]

# Measured closed-loop pairwise comparisons, generated by c4stats.py (paired McNemar on identical
# layouts). Each entry: (class, armA, armB, successA, successB, n_pair). Success values differ
# slightly for the same arm across comparisons because the paired subsets differ -- that is
# correct, and is why this is stored pairwise rather than as one success-per-arm table.
CLOSED_LOOP = [
    # U8_top2 vs dense
    ("chair_04", "top2", "dense", 0.550, 0.000, 20),
    ("chair_05", "top2", "dense", 0.350, 0.000, 20),
    ("cloth_01", "top2", "dense", 0.977, 0.318, 44),
    ("cloth_02", "top2", "dense", 0.050, 0.100, 20),
    ("clothes_hanger_02", "top2", "dense", 0.032, 0.038, 186),
    ("indoor_plant_02", "top2", "dense", 0.260, 0.300, 50),
    ("plant_01", "top2", "dense", 0.550, 0.200, 20),
    ("refrigerator", "top2", "dense", 0.400, 0.311, 45),
    ("umbrella", "top2", "dense", 0.950, 0.400, 20),
    ("wall_cabinet_01", "top2", "dense", 0.833, 0.324, 204),
    ("wall_cabinet_02", "top2", "dense", 0.211, 0.158, 19),
    ("wall_cabinet_03", "top2", "dense", 0.552, 0.138, 29),
    # U8_top1 vs dense
    ("chair_04", "top1", "dense", 0.600, 0.000, 20),
    ("chair_05", "top1", "dense", 0.300, 0.000, 20),
    ("cloth_01", "top1", "dense", 0.929, 0.429, 14),
    ("cloth_02", "top1", "dense", 0.100, 0.100, 20),
    ("clothes_hanger_02", "top1", "dense", 0.550, 0.039, 180),
    ("indoor_plant_02", "top1", "dense", 0.100, 0.300, 50),
    ("plant_01", "top1", "dense", 0.300, 0.200, 20),
    ("refrigerator", "top1", "dense", 0.600, 0.311, 45),
    ("umbrella", "top1", "dense", 0.350, 0.400, 20),
    ("wall_cabinet_01", "top1", "dense", 0.640, 0.335, 164),
    ("wall_cabinet_02", "top1", "dense", 0.158, 0.158, 19),
    ("wall_cabinet_03", "top1", "dense", 0.483, 0.138, 29),
    # vs dense-widen
    ("clothes_hanger_02", "top2", "widen", 0.030, 0.060, 166),
    ("wall_cabinet_01", "top2", "widen", 0.832, 0.352, 179),
    ("clothes_hanger_02", "top1", "widen", 0.524, 0.060, 166),
    ("wall_cabinet_01", "top1", "widen", 0.631, 0.352, 179),
    ("clothes_hanger_02", "widen", "dense", 0.055, 0.034, 145),
    ("wall_cabinet_01", "widen", "dense", 0.374, 0.337, 163),
]

# The two reversals. Derived by comparing each mixture's own vs-dense cell on the same class, so
# they are directional evidence rather than a paired test -- scored separately and labelled.
REVERSALS = [("umbrella", "top2", "top1", 0.950, 0.350),
             ("clothes_hanger_02", "top1", "top2", 0.550, 0.032)]


def load(path):
    per = defaultdict(list)
    for line in open(path):
        r = json.loads(line)
        per[(r["cls"], r["arm"])] += r["frames"]
    return per


def candidates(frames):
    """Every candidate statistic for one (class, arm), all oriented LOWER = safer."""
    if not frames:
        return {}
    out = {}
    mean = np.array([f["mean"] for f in frames])
    absrel = np.array([f["absrel"] for f in frames])
    mx = np.array([f["max"] for f in frames])
    q = np.array([f["q"] for f in frames])          # (F, len(QS))
    hz = np.array([f["haz"] for f in frames])       # (F, len(TAUS))
    near = np.array([f["gt"] for f in frames]) < 1.5

    # --- mean family: the baselines the campaign already showed fail ---
    out["MEAN_absrel"] = float(absrel.mean())
    out["MEAN_signed"] = float(mean.mean())

    # --- tail family: typical tail, i.e. mean over frames of a per-frame upper quantile ---
    for i, qq in enumerate(QS):
        out[f"TAIL_q{int(qq*100)}"] = float(q[:, i].mean())
    # --- worst-frames family: the trajectory is a max, so look high ACROSS frames too ---
    for i, qq in enumerate(QS):
        out[f"WORSTFR_q{int(qq*100)}"] = float(np.quantile(q[:, i], 0.90))
    out["MAX_mean"] = float(mx.mean())
    out["MAX_p90"] = float(np.quantile(mx, 0.90))

    # --- hazard-rate family: fraction of obstacle pixels placed too far by more than tau ---
    for i, t in enumerate(TAUS):
        out[f"HAZ_{t}"] = float(hz[:, i].mean())
        # "one bad frame kills you": fraction of frames with a substantial hazardous patch
        for p in (0.05, 0.15):
            out[f"FRHAZ_{t}_p{int(p*100)}"] = float((hz[:, i] > p).mean())

    # --- near-field restrictions of the same statistics ---
    if near.sum() >= 5:
        out["MEAN_absrel_near"] = float(absrel[near].mean())
        for i, qq in enumerate(QS):
            out[f"TAIL_q{int(qq*100)}_near"] = float(q[near, i].mean())
        for i, t in enumerate(TAUS):
            out[f"HAZ_{t}_near"] = float(hz[near, i].mean())
    return out


def sign_p(k, n):
    """Two-sided exact binomial p under concordance = 1/2."""
    if n == 0:
        return 1.0
    k = max(k, n - k)
    tail = sum(math.comb(n, i) for i in range(k, n + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def score(stats, comparisons, eps):
    ok = tot = 0
    misses = []
    for cls, a, b, sa, sb, *_ in comparisons:
        if abs(sa - sb) < eps:
            continue
        ka, kb = (cls, a), (cls, b)
        if ka not in stats or kb not in stats:
            continue
        tot += 1
        # lower statistic should belong to the arm that flew better
        if (stats[ka] < stats[kb]) == (sa > sb):
            ok += 1
        else:
            misses.append(f"{cls}:{a}v{b}")
    return ok, tot, misses


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", required=True, help="jsonl from tail_metrics.py")
    ap.add_argument("--eps", type=float, default=0.03,
                    help="ignore comparisons whose success gap is below this (no signal)")
    ap.add_argument("--top", type=int, default=18)
    args = ap.parse_args()

    per = load(args.rows)
    stats_by_name = defaultdict(dict)
    for key, frames in per.items():
        for name, val in candidates(frames).items():
            stats_by_name[name][key] = val
    print(f"loaded {len(per)} (class, arm) cells; "
          f"{sum(len(v) for v in per.values())} frames; {len(stats_by_name)} candidates\n")

    results = []
    for name, st in stats_by_name.items():
        ok, tot, misses = score(st, CLOSED_LOOP, args.eps)
        if tot < 8:
            continue
        rok, rtot, _ = score(st, [(c, a, b, sa, sb) for c, a, b, sa, sb in REVERSALS], args.eps)
        results.append((ok / tot, ok, tot, sign_p(ok, tot), rok, rtot, name, misses))
    results.sort(reverse=True)

    print(f"{'statistic':<26} {'concord':>9} {'rate':>6} {'p':>9} {'reversals':>10}")
    print("-" * 70)
    for rate, ok, tot, p, rok, rtot, name, _ in results[:args.top]:
        print(f"{name:<26} {ok:>4}/{tot:<4} {rate:>6.2f} {p:>9.2g} {rok:>6}/{rtot}")

    print("\nBASELINES (the metrics the field actually selects on):")
    for rate, ok, tot, p, rok, rtot, name, miss in results:
        if name.startswith("MEAN"):
            print(f"  {name:<24} {ok}/{tot} = {rate:.2f}  p={p:.2g}  reversals {rok}/{rtot}")

    if results:
        best = results[0]
        print(f"\nBEST: {best[6]}  {best[1]}/{best[2]} = {best[0]:.2f}, p={best[3]:.2g}, "
              f"reversals {best[4]}/{best[5]}")
        if best[7]:
            print(f"  misses: {', '.join(best[7])}")
        print(f"\nMULTIPLE-COMPARISON EXPOSURE: {len(results)} candidates swept. "
              f"Treat the headline as optimistic.")

        # Split validation: pick the winner on half the classes, score it on the held-out half.
        classes = sorted({c for c, *_ in CLOSED_LOOP})
        fit_cls = set(classes[::2])
        held = [x for x in CLOSED_LOOP if x[0] not in fit_cls]
        fit = [x for x in CLOSED_LOOP if x[0] in fit_cls]
        scored = []
        for name, st in stats_by_name.items():
            ok, tot, _ = score(st, fit, args.eps)
            if tot >= 4:
                scored.append((ok / tot, name))
        if scored:
            scored.sort(reverse=True)
            wname = scored[0][1]
            hok, htot, hmiss = score(stats_by_name[wname], held, args.eps)
            print(f"SPLIT VALIDATION: selected '{wname}' on {len(fit_cls)} classes "
                  f"-> held-out {hok}/{htot}"
                  + (f" = {hok/htot:.2f}, p={sign_p(hok, htot):.2g}" if htot else ""))


if __name__ == "__main__":
    main()
